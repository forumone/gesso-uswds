/**
 * Webpack loader for config.design-tokens.yml.
 *
 * This file is ESM TypeScript, loaded directly through Node's native type
 * stripping. Webpack's loader-runner picks up the default export, so no CommonJS
 * is needed.
 */
import os from 'node:os';
import { stringify, type ParsedNode } from 'yaml';
import type { LoaderContext } from 'webpack';

import { readSource } from './readSource.ts';
import { renderJs } from './renderJs.ts';
import { renderSass } from './renderSass.ts';
import { renderUswdsTheme } from './renderUswdsTheme.ts';
import { SassValue, tag as sassTag } from './SassValue.ts';
import { toError } from './toError.ts';
import { transform } from './transform.ts';
import type { ParsedSource, TransformedSource } from './types.ts';
import { UswdsValue, tag as uswdsTag } from './UswdsValue.ts';

export const SASS_OUTPUT_PATH =
  '../source/00-config/_design-tokens.artifact.scss';
export const USWDS_SASS_OUTPUT_PATH =
  '../source/00-config/_uswds-theme-settings.artifact.scss';
export const JS_OUTPUT_PATH = '../source/00-config/_GESSO.source.js';

/** Makes the USWDS theme settings available to the design tokens Sass. */
export const uswdsSassUse = "@use '_uswds-theme-settings.artifact.scss' as *;";

export const sassComment = `// stylelint-disable
// DO NOT EDIT THIS FILE.  This is a gitignored artifact created by Webpack.
// Design tokens should be edited in source/00-config/config.design-tokens.yml`;

export const jsComment = `/* eslint-disable */
// DO NOT EDIT THIS FILE.  This is a gitignored artifact created by Webpack.
// Design tokens should be edited in source/00-config/config.design-tokens.yml`;

/**
 * The pipeline stages the loader depends on. Injectable so the loader can be
 * tested in isolation.
 */
export interface ConfigLoaderDependencies {
  readSource: (source: string) => Promise<ParsedSource<ParsedNode, true>>;
  transform: (parsed: ParsedSource<ParsedNode, true>) => TransformedSource;
  renderSass: typeof renderSass;
  renderUswdsTheme: typeof renderUswdsTheme;
  renderJs: typeof renderJs;
  /** End-of-line sequence placed between the header comment and the output. */
  eol: string;
}

/** The slice of webpack's `LoaderContext` that the loader actually uses. */
export type ConfigLoaderContext = Pick<
  LoaderContext<object>,
  'async' | 'emitFile'
>;

export const defaultDependencies: ConfigLoaderDependencies = {
  readSource,
  transform,
  renderSass,
  renderUswdsTheme,
  renderJs,
  eol: os.EOL,
};

/**
 * Serializes the transformed data back to YAML, writing `SassValue`s as plain
 * `{ sass, fallback }` maps and `UswdsValue`s as their Sass expression
 * (e.g. `units(5)`).
 */
export function stringifyTokens(data: TransformedSource['data']): string {
  return stringify(
    data,
    (_key, value: unknown) =>
      value instanceof SassValue
        ? {
            sass: value.sass,
            fallback: value.fallback,
          }
        : value instanceof UswdsValue
          ? value.toSass()
          : value,
    {
      customTags: [sassTag, uswdsTag],
    }
  );
}

export interface ConfigLoaderOutput {
  sass: string;
  uswdsSass: string;
  js: string;
  yaml: string;
}

/**
 * Runs the full design-token pipeline against the YAML source.
 */
export async function processConfig(
  source: string,
  deps: ConfigLoaderDependencies = defaultDependencies
): Promise<ConfigLoaderOutput> {
  const parsed = await deps.readSource(source);
  const transformed = deps.transform(parsed);

  return {
    sass:
      sassComment +
      deps.eol +
      uswdsSassUse +
      deps.eol +
      deps.renderSass(transformed.data),
    uswdsSass: sassComment + deps.eol + deps.renderUswdsTheme(transformed.data),
    js: jsComment + deps.eol + deps.renderJs(transformed.data),
    yaml: stringifyTokens(transformed.data),
  };
}

/**
 * Creates the loader function with the given dependencies.
 */
export function createConfigLoader(
  deps: ConfigLoaderDependencies = defaultDependencies
) {
  /**
   * Creates the processed JavaScript and Sass files and then calls the
   * async callback with the transformed YAML. Any failure, synchronous or from
   * a rejected promise, is passed to the callback.
   */
  return function configLoader(
    this: ConfigLoaderContext,
    source: string
  ): void {
    const callback = this.async();
    processConfig(source, deps)
      .then(output => {
        this.emitFile(USWDS_SASS_OUTPUT_PATH, output.uswdsSass);
        this.emitFile(SASS_OUTPUT_PATH, output.sass);
        this.emitFile(JS_OUTPUT_PATH, output.js);
        return output.yaml;
      })
      .then(
        yaml => {
          callback(null, yaml);
        },
        (error: unknown) => {
          callback(toError(error));
        }
      );
  };
}

export default createConfigLoader();
